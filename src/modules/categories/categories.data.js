export async function seedInitialCategories() {
  try {
    const existingCount = await Category.countDocuments({});
    if (existingCount >= 500) {
      logger.info(`Categories already populated (${existingCount} items).`);
      return;
    }

    logger.info("Initializing 500+ categories and subcategories into database...");

    const operations = [];

    for (const [catName, subList] of Object.entries(INITIAL_CATEGORIES_DATA)) {
      const catSlug = generateSlug(catName);
      operations.push({
        updateOne: {
          filter: { slug: catSlug },
          update: {
            $set: {
              name: catName,
              slug: catSlug,
              parent: "",
              status: "Active"
            }
          },
          upsert: true
        }
      });

      for (const subName of subList) {
        const subSlug = generateSlug(`${catName}-${subName}`);
        operations.push({
          updateOne: {
            filter: { slug: subSlug },
            update: {
              $set: {
                name: subName,
                slug: subSlug,
                parent: catName,
                status: "Active"
              }
            },
            upsert: true
          }
        });
      }
    }

    if (operations.length > 0) {
      const res = await Category.bulkWrite(operations, { ordered: false });
      const totalNow = await Category.countDocuments({});
      logger.info(`Categories seed complete! Upserted: ${res.upsertedCount}, Modified: ${res.modifiedCount}, Total in DB: ${totalNow}`);
    }
  } catch (err) {
    logger.error("Error seeding initial categories:", err);
  }
}
